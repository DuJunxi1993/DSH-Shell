#!/usr/bin/env python3
"""Build the dsh-shell app icon.

    python scripts/extract-dsh-whale.py   # refresh the whale from dsh (optional)
    python scripts/make-icon.py
    cargo tauri icon src-tauri/icons/dsh-shell.png

The whale comes from `src-tauri/icons/dsh-whale.png`, an 8-bit coverage mask
generated by `extract-dsh-whale.py` from **dsh's own `FISH_LOGO_PATH`**, rendered
on its `FISH_LOGO_VIEWBOX`. That file is committed, so this script and the build
do not need dsh installed; run the extractor after a dsh upgrade.

Note which mark that is. dsh ships the whale twice, and they are not the same
path: `FISH_LOGO_PATH` (23.16 x 17.04) is what its own UI draws as the logo, and
`favicon.svg` (50 x 50) is the browser-tab mark. The mask this replaced was built
from the *favicon*, which is why it sat about two percent off dsh's UI mark — see
`docs/cross-platform-lessons.md` §1. macOS draws `FISH_LOGO_PATH` in its menu bar,
so using it here is also what makes the two shells carry the same whale.

The mark is plated on a gradient rather than shipped as dsh's own icon, so the
dsh-shell icon is distinguishable at a glance from the dsh *web* icon in a
browser.

## The design, and what each part is doing

`scripts/icon-sample.py` renders candidates at other sizes and colours without
touching the repo; it imports `build()` from here, so there is one copy of the
geometry.

* **Plate** — the gradient sampled from `logo_background.png` rather than chosen
  by eye. That image is 836x850, transparent rounded corners, opaque from y=101 on
  the left edge: radius/width = 101/836 = **12.1%**, and the plate spans the full
  canvas (opaque bbox 1..834, so no inset). Fitted as a linear gradient along the
  **diagonal** — a vertical gradient would put two visibly different colours either
  side of the whale, because in the source image the colour changes along x as well
  (mid-height: `#5470EB` at the left, `#7030EF` at the right). Interior residuals
  are under 9/255, i.e. 8-bit rounding.
* **Mark size** — a fraction of the **plate**, not of the canvas, and applied to
  the mask's *ink* rather than to its square. Both matter: the mask is a square
  with the viewBox letterboxed inside it, so the whale only fills the middle ~73%,
  and sizing the square made the mark `0.62 x 0.73 = 45%` of the canvas against a
  plate spanning 89%. The eye compares the mark to the plate, so `build()` crops to
  the ink first and then scales to `WHALE_FRACTION` of the plate width.
* **Mark colour** — near-white. The plate is a saturated blue-to-purple gradient,
  and the brand blue this replaced was both the same hue as the plate and at almost
  the same value, so it had no contrast against it. Near-white is the one colour
  guaranteed to read against a gradient of this kind.

The old dark plate and its "glass sheen" are gone; they were a different design,
not a parameter of this one.

Requires Pillow.
"""

from __future__ import annotations

import math
import sys
from pathlib import Path

from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parent.parent
WHALE = ROOT / "src-tauri" / "icons" / "dsh-whale.png"
OUT = ROOT / "src-tauri" / "icons" / "dsh-shell.png"

CANVAS = 1024

# The plate's colour is sampled from `logo_background.png`; its *shape* comes from
# the reference the user supplied, which is a macOS-style squircle.
#
# `logo_background.png` is 836x850, transparent rounded corners, opaque from y=101
# on the left edge, so its own radius/width is 12.1% and it is full-bleed.
#
# The colour is a linear gradient along the **diagonal**. A vertical gradient would
# put two visibly different colours either side of the mark, because in that image
# the colour changes along x as well — at mid height it runs `#5470EB` on the left to
# `#7030EF` on the right. Interior residuals are under 9/255, i.e. 8-bit rounding.
PLATE_INSET = 0
GRADIENT_FROM = (61, 154, 245)   # #3D9AF5, top-left
GRADIENT_TO = (134, 11, 236)     # #860BEC, bottom-right

# The corner, as a plain circular radius.
#
# `PLATE_CORNER_FRACTION` was measured from the reference the user supplied, by
# rendering candidates at the reference's own 30x30 size through this file's
# rasterisation and comparing the edge profile row by row. The reference's
# profile is
#
#     [4, 2, 1, 1, 0, 0, ..., 0, 1, 1, 2, 4]
#
# and a circular corner of 20% reproduces it *exactly* — 0.000px mean error over
# all thirty rows. 22% is 0.133px off and 12% (what this used to be) is 0.333px
# off, which is the whole difference between "a little rounder" and "matching".
#
# A macOS squircle was tried and rejected: at the reference's size it fits
# *worse* (0.400px), because the squircle's corner leaves the straight edge
# sooner, and what the reference has is a round corner that simply reaches
# further. The squircle code is gone rather than left as a knob, because it is
# not what the reference shows and it was twice implemented wrongly.
PLATE_CORNER_FRACTION = 0.20

# The plate mask is rendered large and scaled down, because the analytic edge it
# computes is exact but not antialiased.
PLATE_SUPERSAMPLE = 4

# The mark, as a fraction of the plate's width. Chosen from `icon-sample.py`'s
# 0.72 / 0.80 / 0.88 candidates at taskbar size: 0.88 pushes the tail into the
# top-right corner and turns to mush at 32px, 0.72 is closest to the share dsh's
# own favicon gives the whale.
WHALE_FRACTION = 0.72

WHALE_TOP = (255, 255, 255)
WHALE_BOTTOM = (233, 240, 255)

# Softens the mask's edge a little; LANCZOS already antialiased the downscale,
# and this is only to take the last hard pixel off it.
WHALE_BLUR = 1.2


def squircle_mask(
    size: int,
    corner_fraction: float = PLATE_CORNER_FRACTION,
    exponent: float = 2.0,
    supersample: int = PLATE_SUPERSAMPLE,
) -> Image.Image:
    """The plate's shape: a rounded rectangle with a circular corner.

    Named for what it replaces rather than for what it is — the name is kept so the
    diff against the squircle version reads as "same thing, rounder corner" — but
    the corner is a plain arc.

    `exponent` is accepted and ignored, because the reference turned out to be a
    circular corner: see `PLATE_CORNER_FRACTION`. It stays as a parameter so the
    sample script can still ask for the alternatives and show that they fit
    worse.
    """
    big = size * supersample
    radius = min(corner_fraction * big, big / 2.0)
    if radius <= 0:
        raise ValueError("the corner must have some extent")

    mask = Image.new("L", (big, big), 0)
    pixels = mask.load()
    flat = big / 2.0 - radius
    for y in range(big):
        dy = abs((y + 0.5) - big / 2.0)
        if dy <= flat:
            inset = 0.0
        else:
            u = (dy - flat) / radius
            # A circular corner: the inset is r - sqrt(r^2 - (r - dy)^2).
            inset = radius * (1.0 - (1.0 - u * u) ** 0.5)
        first = int(math.ceil(inset))
        last = int(math.floor(big - inset))
        for x in range(first, last):
            pixels[x, y] = 255

    if supersample == 1:
        return mask
    return mask.resize((size, size), Image.LANCZOS)


def build(
    whale_fraction: float = WHALE_FRACTION,
    corner_fraction: float = PLATE_CORNER_FRACTION,
    corner_exponent: float = 2.0,
    whale_top: tuple[int, int, int] = WHALE_TOP,
    whale_bottom: tuple[int, int, int] = WHALE_BOTTOM,
    blur: float = WHALE_BLUR,
) -> Image.Image:
    """The plated icon, at `CANVAS` square. Every knob has a default."""
    plate_size = CANVAS - 2 * PLATE_INSET

    plate = squircle_mask(CANVAS, corner_fraction, corner_exponent)

    # Diagonal gradient, clipped to the plate.
    base = Image.new("RGBA", (CANVAS, CANVAS))
    pixels = base.load()
    span = CANVAS - 1
    for y in range(CANVAS):
        ty = y / span
        for x in range(CANVAS):
            t = (x / span + ty) / 2.0
            colour = tuple(
                round(GRADIENT_FROM[i] + (GRADIENT_TO[i] - GRADIENT_FROM[i]) * t)
                for i in range(3)
            )
            pixels[x, y] = (*colour, 255)
    base.putalpha(plate)

    whale = Image.open(WHALE)
    if whale.mode != "L":
        raise SystemExit(f"{WHALE.name} must be an 8-bit alpha mask, got {whale.mode}")

    # Crop to the ink before sizing. The mask is a square with the viewBox
    # letterboxed inside it, so scaling the square would leave the mark at ~73% of
    # the size asked for — which is most of why it read as too small.
    ink = whale.crop(whale.getbbox())
    width = int(plate_size * whale_fraction)
    height = max(1, round(width / (ink.width / ink.height)))
    mask = ink.resize((width, height), Image.LANCZOS)
    if blur:
        mask = mask.filter(ImageFilter.GaussianBlur(blur))

    # A slight vertical falloff, so the mark has some form instead of reading as
    # a flat sticker on a flat gradient.
    tinted = Image.new("RGBA", mask.size)
    tp = tinted.load()
    span_y = max(1, mask.size[1] - 1)
    for y in range(mask.size[1]):
        t = y / span_y
        colour = tuple(
            round(whale_top[i] + (whale_bottom[i] - whale_top[i]) * t) for i in range(3)
        )
        for x in range(mask.size[0]):
            tp[x, y] = (*colour, 255)
    tinted.putalpha(mask)

    base.alpha_composite(
        tinted, ((CANVAS - width) // 2, (CANVAS - mask.size[1]) // 2)
    )
    return base


def main() -> int:
    if not WHALE.exists():
        print(f"missing {WHALE}", file=sys.stderr)
        return 1
    icon = build()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    icon.save(OUT)
    print(f"wrote {OUT} ({icon.size[0]}x{icon.size[1]})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

/* dsh-shell window chrome, injected into every document the webview loads.
 *
 * The page is REMOTE and we do not control its stylesheet, so this file is
 * written to lose gracefully:
 *
 *  * The stylesheet carries background and hover colours only. Sizes and radii
 *    are inline, because they are geometry and have to track the page zoom, and
 *    because an inline `background` would beat every `:hover` rule in the
 *    stylesheet - which is exactly how the hover highlights went missing once.
 *  * The bar hangs off `document.documentElement`, not `body`, so nothing the
 *    page does to its own root container can capture it.
 *  * It is injected twice on purpose. `initialization_script` does not survive
 *    dsh's Content-Security-Policy, so the real page gets this from Rust via
 *    `eval` on page load; the early return below makes that idempotent.
 *
 * ## Zoom
 *
 * The page is zoomed (Ctrl +/-/0); the chrome is not. The geometry arrives from
 * Rust (`window.__DSH_SHELL__`) and every length goes through `px()`, which
 * divides by the page zoom exactly once. Do not also counter-scale with a
 * transform: that was the bug where zooming out made the buttons grow.
 * `chrome_report` re-measures the live DOM and Rust fails the run if
 * `height * zoom !== barH`.
 *
 * ## Clicking through
 *
 * The bar carries the three window buttons and nothing else. It is
 * `pointer-events: none` apart from the buttons, and it draws no background, so
 * the page's own content reaches every pixel of the window the buttons are not
 * sitting on.
 *
 * ## The page's own layout
 *
 * dsh reserves the caption. There is no geometric pass here any more: the
 * contract is declared, and the only thing left to do is read back whether dsh
 * answered. Insetting a column found by its geometry was a guess about a
 * document whose class names are rehashed every dsh build, and a wrong guess
 * displaces the page's own layout.
 */
(function () {
  "use strict";

  if (window.__DSH_SHELL_CHROME__) {
    return;
  }

  /* Every value below is generated by chrome.rs and injected as
     window.__DSH_SHELL__; the fallback is only for the case where the script is
     evaluated without it. They are kept in step with the Rust constants by
     chrome::tests - a fallback that drifts is a silently wrong chrome, which is
     how the bar was once 28px tall in the page and 24 in the crate. */
  var CFG = window.__DSH_SHELL__ || {};
  var BAR_H = num(CFG.barH, 28);
  var WIN_W = num(CFG.winW, 32);
  var CORNER_R = num(CFG.cornerR, 5);
  var RESERVED_W = 3 * WIN_W;

  /* The ladder comes from config.rs too. It is not restated here: the key
     handler needs the step to ask for and clampZoom needs both ends, and a ladder
     written down twice is a ladder that disagrees with itself. */
  var ZOOM_MIN = num(CFG.zoomMin, 50);
  var ZOOM_MAX = num(CFG.zoomMax, 200);
  var ZOOM_STEP = num(CFG.zoomStep, 10);

  var STYLE_ID = "dsh-shell-chrome-style";
  var ROOT_ID = "dsh-shell-chrome";

  /* Gap between the top of the window and the button row. Native captions are
     flush against the frame, but on a frameless window the buttons sit on the
     page and read as glued to the edge without it. */
  var BUTTON_GAP = 4;

  /* ===================================================================
   * LAYER 1 — the desktop contract
   * ===================================================================
   *
   * dsh publishes a desktop-host contract, and this file used to ignore it and
   * compensate geometrically instead. Declaring the host costs two properties:
   *
   *   document.documentElement.setAttribute('data-windows-titlebar', '')
   *   --dsh-windows-titlebar-height: <our bar height>
   *
   * dsh then reserves the caption height on its own frame, paints its own drag
   * strip, rounds the content column's top-left corner, publishes
   * `--dsh-frame-chrome-top`, insets its own fullscreen modal overlays, and
   * converges both of those when the window goes fullscreen. Measured, not
   * assumed: see docs/dsh-desktop-contract.md §2.3.
   *
   * Note what dsh does *not* provide: a caption with buttons. It reserves space
   * and offers a drag region; the three window buttons stay ours, because they
   * are the only part of a native caption that talks to the window manager.
   *
   * The height is ours to declare, so it comes from the same constant as every
   * other length here and goes through `px()` like all of them. Declaring it in
   * logical pixels would be wrong: dsh reads it as a CSS length and the page
   * zoom multiplies it, exactly like everything else in the document.
   *
   * `--dsh-windows-titlebar-height` is *read* by dsh and never set by it, which
   * is what makes the host the owner of the number.
   */
  function declareDesktopContract() {
    var html = document.documentElement;
    if (!html) return;
    try {
      if (!html.hasAttribute("data-windows-titlebar")) {
        html.setAttribute("data-windows-titlebar", "");
      }
      html.style.setProperty("--dsh-windows-titlebar-height", px(BAR_H));
    } catch (error) {
      /* A document that refuses the attribute still gets the fallback layer. */
      reportContract("contractMissing", String(error));
    }
  }

  /* Whether dsh is honouring the contract.
   *
   * The test is whether dsh has *published* something in response, not whether
   * our attribute is present: an attribute we set is only a claim, and a dsh
   * that predates the contract will ignore it silently. Reading back
   * `--dsh-frame-chrome-top` is the conversation. */
  function contractState() {
    var html = document.documentElement;
    if (!html) return "contractMissing";
    /* Our own boot placeholder is not dsh and has no contract to honour. */
    if (html.hasAttribute("data-dsh-shell-placeholder")) return "contractMissing";
    try {
      var published = window.getComputedStyle(html)
        .getPropertyValue("--dsh-frame-chrome-top").trim();
      return published ? "contractActive" : "contractMissing";
    } catch (error) {
      return "contractMissing";
    }
  }

  /* dsh's reserved height, in logical pixels, or null when it publishes none.
   * Read-only, and reported so the log says how much room dsh claimed rather
   * than leaving the number to be inferred from a screenshot. */
  function contractTopClearance() {
    if (contractState() !== "contractActive") return null;
    try {
      var raw = window.getComputedStyle(document.documentElement)
        .getPropertyValue("--dsh-frame-top-clearance").trim();
      if (!raw) return null;
      var parsed = parseFloat(raw);
      return isFinite(parsed) && parsed > 0 ? parsed : null;
    } catch (error) {
      return null;
    }
  }

  var contractReport = "contractMissing";

  function reportContract(state, detail) {
    contractReport = state;
    try {
      window.__DSH_SHELL_CONTRACT__ = {
        state: state,
        detail: detail || null,
        topClearance: contractTopClearance()
      };
    } catch (error) {
      /* Nothing to do: the diagnostic is best-effort by construction. */
    }
  }

  var zoom = clampZoom(num(CFG.zoom, 100));
  var z = zoom / 100;

  function num(value, fallback) {
    var parsed = Number(value);
    return isFinite(parsed) && parsed > 0 ? parsed : fallback;
  }

  function clampZoom(value) {
    if (!isFinite(value)) return ZOOM_MAX;
    if (value < ZOOM_MIN) return ZOOM_MIN;
    if (value > ZOOM_MAX) return ZOOM_MAX;
    return value;
  }

  /* The one place page zoom is divided out. See chrome::css_len.
     Two forms: `cssPx` for arithmetic and hit-testing, `px` for a CSS length.
     Using the string form in arithmetic yields NaN. */
  function cssPx(designPx) {
    return designPx / z;
  }

  function px(designPx) {
    return cssPx(designPx) + "px";
  }

  function invoke(cmd, args) {
    // `withGlobalTauri` is off, so the bridge is the internals object. Fall back
    // to the global API in case a future config turns it on.
    var internals = window.__TAURI_INTERNALS__;
    if (internals && typeof internals.invoke === "function") {
      return internals.invoke(cmd, args || {});
    }
    if (window.__TAURI__ && window.__TAURI__.core) {
      return window.__TAURI__.core.invoke(cmd, args || {});
    }
    return Promise.reject(new Error("no tauri bridge on this origin"));
  }

  /* Backgrounds and hover states live here, not inline: an inline background
     would beat every `:hover` rule in the stylesheet and the highlight would
     never show. The zoom and the sizes are still inline, because they are
     geometry and have to track the page zoom from one place.
   *
   * A constructed stylesheet is used rather than a `<style>` element because our
   * own boot page's CSP drops injected style elements - the buttons then fell
   * back to the UA default grey border and fill, which is the white outline seen
   * during startup. Constructed sheets are not subject to the page's CSP. */
  function installStylesheet() {
    var css = [
      "#" + ROOT_ID + " button {",
      "  background: transparent;",
      "  border: 0;",
      "  outline: none;",
      "  color: inherit;",
      "  cursor: default;",
      "}",
      "#" + ROOT_ID + " button:hover {",
      "  background: rgba(127,127,127,0.22);",
      "}",
      /* Light red, not a solid fill: the cluster behind it is the page's own
         surface colour, and a solid block there reads as a foreign panel. */
      "#" + ROOT_ID + " .dss-win button[data-dss-close]:hover {",
      "  background: rgba(214,45,45,0.18);",
      "}",
      "#" + ROOT_ID + " .dss-win button[data-dss-close]:hover svg g {",
      "  stroke: #c0392b;",
      "}",
      "#" + ROOT_ID + " svg { display: block; }"
    ].join("\n");

    try {
      if (window.CSSStyleSheet) {
        var sheet = new CSSStyleSheet();
        sheet.replaceSync(css);
        document.adoptedStyleSheets = document.adoptedStyleSheets.concat([sheet]);
        return;
      }
    } catch (error) {
      /* Older engines, or a document that forbids constructed sheets: the
         element below still works on the dsh origin. */
    }

    if (document.getElementById(STYLE_ID)) {
      return;
    }
    var style = document.createElement("style");
    style.id = STYLE_ID;
    style.textContent = css;
    (document.head || document.documentElement).appendChild(style);
  }

  /* A window glyph in a 10x10 viewBox. `currentColor` so it follows the host
     page's foreground, and a presentation attribute rather than an inline style
     so the close hover can override the colour from the stylesheet. */
  function glyph(kind) {
    var ns = "http://www.w3.org/2000/svg";
    var svg = document.createElementNS(ns, "svg");
    svg.setAttribute("viewBox", "0 0 10 10");
    svg.setAttribute("width", px(10));
    svg.setAttribute("height", px(10));
    svg.setAttribute("aria-hidden", "true");

    var shape = document.createElementNS(ns, "g");
    shape.setAttribute("stroke", "currentColor");
    shape.setAttribute("stroke-width", "1.1");
    shape.setAttribute("fill", "none");
    shape.setAttribute("stroke-linecap", "round");

    function node(tag, attrs) {
      var el = document.createElementNS(ns, tag);
      for (var key in attrs) {
        if (Object.prototype.hasOwnProperty.call(attrs, key)) {
          el.setAttribute(key, attrs[key]);
        }
      }
      shape.appendChild(el);
      return el;
    }

    if (kind === "min") {
      node("line", { x1: 0, y1: 5, x2: 10, y2: 5 });
    } else if (kind === "max") {
      node("rect", { x: 0.5, y: 0.5, width: 9, height: 9 });
    } else if (kind === "restore") {
      node("rect", { x: 0.5, y: 2.5, width: 7, height: 7 });
      node("rect", { x: 2.5, y: 0.5, width: 7, height: 7 });
    } else {
      node("line", { x1: 0, y1: 0, x2: 10, y2: 10 });
      node("line", { x1: 10, y1: 0, x2: 0, y2: 10 });
    }
    svg.appendChild(shape);
    return svg;
  }

  function describe(el) {
    if (!el) {
      return "none";
    }
    var r = el.getBoundingClientRect();
    var name = typeof el.className === "string" ? el.className : "";
    if (name.length > 40) {
      name = name.slice(0, 40) + "…";
    }
    return (
      el.tagName.toLowerCase() +
      (el.id ? "#" + el.id : "") +
      (name ? "." + name : "") +
      " [" + Math.round(r.left) + "," + Math.round(r.top) +
      " " + Math.round(r.width) + "x" + Math.round(r.height) + "]"
    );
  }

  function install() {
    installStylesheet();
    /* Declared before the bar is built so the chrome and the page's own
       reservation appear together rather than as two separate reflows. This is
       the only thing this file does to dsh: two properties on <html>. */
    declareDesktopContract();

    var bar = document.createElement("div");
    bar.id = ROOT_ID;
    bar.style.cssText = [
      "position:fixed",
      "top:0",
      "left:0",
      "right:0",
      "margin:0",
      "padding:0",
      "border:0",
      "display:flex",
      "align-items:flex-start",
      "height:" + px(BAR_H),
      "z-index:2147483647",
      /* Everything below is click-through except the window buttons. */
      "pointer-events:none",
      "color:var(--dsw-alias-label-primary, #16181d)",
      "-webkit-user-select:none",
      "user-select:none"
    ].join(";");

    /* --- adaptive foreground colour ---
     *
     * The bar is chrome over a page we do not control, and dsh ships a dark
     * theme. The glyphs are `currentColor` and the buttons inherit, so their
     * colour resolves to this bar's `color: var(--dsw-alias-label-primary,
     * #16181d)`. That fallback is near-black, which is correct on a light page and
     * invisible on a dark one — and dsh's dark theme does not always define the
     * alias, so the bar fell back to it and the window buttons vanished.
     *
     * Rather than guess dsh's theme tokens (which differ per build, and are not
     * guaranteed on `<html>` at all), measure the surface the bar actually sits on
     * and pick a foreground with contrast against it. This reacts to a theme
     * switch on its own, and works for the boot page and dsh alike.
     */

    /* Parse a CSS colour into 0..255 channels. Handles the rgb()/rgba() form the
     * computed style always yields, and a hex token for the custom properties.
     * Returns null for anything it cannot read, so the caller can fall through to
     * the next candidate rather than trusting a parse of "inherit". */
    function parseColor(value) {
      if (!value) {
        return null;
      }
      var text = String(value).trim();
      var rgb = text.match(/rgba?\(\s*([\d.]+)[,\s]+([\d.]+)[,\s]+([\d.]+)/i);
      if (rgb) {
        return {
          r: parseFloat(rgb[1]),
          g: parseFloat(rgb[2]),
          b: parseFloat(rgb[3])
        };
      }
      var hex = text.match(/^#?([0-9a-f]{6})$/i) || text.match(/^#?([0-9a-f]{3})$/i);
      if (hex) {
        var h = hex[1];
        if (h.length === 3) {
          h = h[0] + h[0] + h[1] + h[1] + h[2] + h[2];
        }
        return {
          r: parseInt(h.slice(0, 2), 16),
          g: parseInt(h.slice(2, 4), 16),
          b: parseInt(h.slice(4, 6), 16)
        };
      }
      return null;
    }

    /* WCAG relative luminance, 0 (black) to 1 (white). The threshold is not
     * 0.5: a mid grey is the worst case for both, and 0.45 keeps dark-on-mid
     * readable without washing out a light page. */
    function luminance(rgb) {
      function channel(value) {
        var c = value / 255;
        return c <= 0.03928 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4);
      }
      return 0.2126 * channel(rgb.r) + 0.7152 * channel(rgb.g) + 0.0722 * channel(rgb.b);
    }

    /* The colour actually painted behind the bar. Walk the theme token dsh uses,
     * then the document's own surfaces, and take the first opaque one. The bar is
     * transparent, so this is the page's own colour showing through it. */
    function pageBackground() {
      var candidates = [];
      try {
        var rootStyle = getComputedStyle(document.documentElement);
        candidates.push(rootStyle.getPropertyValue("--dsw-alias-bg-base"));
        candidates.push(rootStyle.backgroundColor);
        candidates.push(getComputedStyle(document.body).backgroundColor);
        candidates.push(rootStyle.getPropertyValue("background"));
      } catch (error) {
        /* A document too early to compute a style; the white default below stands. */
      }
      for (var i = 0; i < candidates.length; i++) {
        var rgb = parseColor(candidates[i]);
        if (rgb && (candidates[i].indexOf("rgba") < 0 || candidates[i].indexOf(", 0)") < 0)) {
          return rgb;
        }
      }
      /* Unknown: assume the light default dsh boots with. */
      return { r: 255, g: 255, b: 255 };
    }

    var lastFg = null;
    function probeTheme() {
      var bg = pageBackground();
      var fg = luminance(bg) < 0.45 ? "#e6e6e6" : "#16181d";
      if (fg !== lastFg) {
        bar.style.color = fg;
        lastFg = fg;
      }
      return fg;
    }

    /* --- window buttons --- */
    var winCluster = document.createElement("div");
    winCluster.className = "dss-cluster dss-win";
    winCluster.style.cssText = [
      "display:flex",
      "align-items:stretch",
      "pointer-events:auto",
      "margin-left:auto",
      /* A small gap so the buttons do not look glued to the top frame. */
      "margin-top:" + px(BUTTON_GAP),
      "width:" + px(RESERVED_W),
      "height:" + px(BAR_H - BUTTON_GAP),
      "flex:0 0 auto",
      /* No background at all. The bar is chrome over the page, and a fill here
         reads as a foreign panel: it did not match the loaded page or the
         content column. Legibility comes from the glyph colour instead, which
         follows the page's own `--dsw-alias-label-primary` and so works on the
         light dsh theme and on the dark boot page alike. */
      "background:transparent"
    ].join(";");

    function control(title, child) {
      var button = document.createElement("button");
      button.type = "button";
      button.className = "dss-btn";
      button.title = title;
      button.setAttribute("aria-label", title);
      button.style.cssText = [
        "appearance:none",
        "-webkit-appearance:none",
        "margin:0",
        "padding:0",
        "display:flex",
        "align-items:center",
        "justify-content:center",
        /* Geometry, all inline so it tracks the zoom from one place. The
           background deliberately is not inline: see installStylesheet. */
        "width:" + px(WIN_W),
        "height:" + px(BAR_H),
        "border-radius:" + px(CORNER_R)
      ].join(";");
      button.appendChild(child);
      return button;
    }

    var minimize = control("Minimize", glyph("min"));
    var maximize = control("Maximize", glyph("max"));
    var close = control("Close", glyph("close"));
    close.setAttribute("data-dss-close", "");

    minimize.addEventListener("click", function () {
      invoke("plugin:window|minimize").catch(function () {});
    });
    maximize.addEventListener("click", function () {
      invoke("plugin:window|toggle_maximize").catch(function () {});
    });
    /* Hides to the tray instead of closing. The window has no native caption,
       so the tray is the only way out from here - which is why Alt+F4 is
       deliberately not routed through this: it still closes the window for
       real, so there is always an exit that does not require finding the tray.
       Closing would otherwise raise ExitRequested and kill dsh, which is no
       longer what this button means. */
    close.addEventListener("click", function () {
      invoke("hide_to_tray").catch(function () {});
    });

    winCluster.appendChild(minimize);
    winCluster.appendChild(maximize);
    winCluster.appendChild(close);
    bar.appendChild(winCluster);

    document.documentElement.appendChild(bar);

    function paint(value) {
      zoom = clampZoom(value);
      z = zoom / 100;
      bar.style.height = px(BAR_H);
      winCluster.style.width = px(RESERVED_W);
      winCluster.style.marginTop = px(BUTTON_GAP);
      winCluster.style.height = px(BAR_H - BUTTON_GAP);
      var buttons = [minimize, maximize, close];
      for (var i = 0; i < buttons.length; i++) {
        buttons[i].style.width = px(WIN_W);
        buttons[i].style.height = px(BAR_H - BUTTON_GAP);
        buttons[i].style.borderRadius = px(CORNER_R);
      }
      var glyphs = winCluster.querySelectorAll("svg");
      for (var g = 0; g < glyphs.length; g++) {
        glyphs[g].setAttribute("width", px(10));
        glyphs[g].setAttribute("height", px(10));
      }
    }

    paint(zoom);

    /* The foreground is measured rather than derived from a token, and a theme
       switch is not something an observer can see: it would watch childList, and
       swapping a theme is a class or custom-property change on an existing node.
       `probeTheme` only touches the DOM when the colour actually changed, so a
       slow poll costs a handful of computed-style reads a second. */
    setInterval(probeTheme, 1500);
    probeTheme();

    window.__DSH_SHELL_CHROME__ = {
      setZoom: paint,
      setMaximized: function (isMaximized) {
        maximize.title = isMaximized ? "Restore" : "Maximize";
        maximize.setAttribute("aria-label", maximize.title);
        var old = maximize.querySelector("svg");
        var fresh = glyph(isMaximized ? "restore" : "max");
        fresh.setAttribute("width", px(10));
        fresh.setAttribute("height", px(10));
        if (old) {
          maximize.replaceChild(fresh, old);
        } else {
          maximize.appendChild(fresh);
        }
      }
    };

    /* What the page sees for `Notification.permission`.
     *
     * Worth reporting because a plugin that shows system notifications is dead
     * unless this is "granted", and the failure is silent: dsh-notification, for
     * one, checks this itself and returns a message nobody ever sees. The value
     * is the notification plugin's shim rather than the browser's, so it really
     * reports whether the ACL allowed the call. Measured the way the plugin
     * measures it, so this is what the plugin would decide on. */
    function notificationState() {
      if (typeof Notification === "undefined") {
        return "absent";
      }
      return Notification.permission;
    }

    /* Tell Rust what happened. The chrome lives in a document we do not own, so
       this is how a broken injection becomes a log line instead of a frameless
       window with no close button. */
    function report(stillPresent) {
      var node = stillPresent ? document.getElementById(ROOT_ID) : null;
      var barBox = node ? node.getBoundingClientRect() : null;
      var winBox = stillPresent ? winCluster.getBoundingClientRect() : null;
      invoke("chrome_report", {
        report: {
          installed: true,
          still_present: !!node,
          /* Multiplied by the page zoom so Rust can compare against the design
             constants it owns: a mismatch means the 1/zoom correction was
             applied a different number of times than exactly once. */
          measured_bar_h: barBox ? barBox.height * z : 0,
          measured_win_w: winBox ? winBox.width * z : 0,
          zoom: z,
          placeholder: document.documentElement.hasAttribute("data-dsh-shell-placeholder"),
          ready_state: document.readyState,
          origin: location.origin,
          notifications: notificationState(),
          /* Whether dsh reserved the caption for us. "contractActive" means the
             page's own top row starts below the bar; "contractMissing" means
             nothing is reserving it and the row runs under the chrome. */
          contract: contractState(),
          contract_top_clearance: contractTopClearance(),
          boxes: "bar=" + describe(node) +
            " winc=" + describe(winCluster) +
            " close=" + describe(close) +
            " color=" + getComputedStyle(node || bar).color
        }
      }).catch(function () {});
    }

    report(true);
    setTimeout(function () {
      report(!!document.getElementById(ROOT_ID));
    }, 1500);

    /* Make the page's Notification permission usable.
     *
     * The page's `Notification` is not the browser's: the notification plugin
     * replaces `window.Notification` with a shim that forwards to Rust, so what
     * this reads and asks is Tauri's, not WebView2's. On desktop the Rust side
     * answers `granted` unconditionally, so the only thing that can refuse is the
     * ACL - and a refusal is silent here, which is how a plugin like
     * dsh-notification ends up doing nothing at all.
     *
     * Asked once per load, because the shim starts every document at "denied" on
     * Windows and something has to ask. The dsh origin only: the boot placeholder
     * has no notifications to show, and asking there would just be noise. */
    if (
      typeof Notification !== "undefined" &&
      location.hostname !== "tauri.localhost" &&
      Notification.permission !== "granted"
    ) {
      try {
        Notification.requestPermission().then(function (result) {
          /* Re-report so the result lands in the log next to the rest of the
             chrome diagnostics, whether it is "granted" or "denied". */
          report(!!document.getElementById(ROOT_ID));
        });
      } catch (error) {
        /* The page's console is not ours to read, so a refusal has to come back
           the same way the rest of the chrome's failures do. */
        invoke("chrome_error", {
          message: "Notification.requestPermission threw: " + error
        }).catch(function () {});
      }
    }
  }

  function paintZoom(value) {
    if (window.__DSH_SHELL_CHROME__ && typeof window.__DSH_SHELL_CHROME__.setZoom === "function") {
      window.__DSH_SHELL_CHROME__.setZoom(value);
    }
  }

  /* Zoom shortcuts. Handled here because focus is inside the page, not the
     window, and `code` is used so the bindings do not depend on the keyboard
     layout: Ctrl+= (and Ctrl+Shift+=) zooms in, Ctrl+- out, Ctrl+0 resets.
     Chromium's own zoom hotkeys are disabled in Rust so these cannot double up. */
  document.addEventListener("keydown", function (event) {
    if (!event.ctrlKey || event.altKey || event.metaKey) {
      return;
    }
    var code = event.code;
    var command = null;
    var delta = 0;
    if (code === "Equal" || code === "NumpadAdd") {
      command = "zoom_step";
      delta = ZOOM_STEP;
    } else if (code === "Minus" || code === "NumpadSubtract") {
      command = "zoom_step";
      delta = -ZOOM_STEP;
    } else if (code === "Digit0" || code === "Numpad0") {
      command = "zoom_reset";
    }
    if (!command) {
      return;
    }
    event.preventDefault();
    invoke(command, command === "zoom_reset" ? {} : { delta: delta })
      .then(paintZoom)
      .catch(function () {});
  });

  function run() {
    try {
      install();
    } catch (error) {
      // Without this, a throw here leaves a frameless window with no way to
      // close it and nothing in the log to explain why.
      invoke("chrome_error", { message: String((error && error.stack) || error) }).catch(function () {});
    }
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", run, { once: true });
  } else {
    run();
  }
})();
